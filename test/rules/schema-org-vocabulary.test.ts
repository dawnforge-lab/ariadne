import { readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";
import { SCHEMA_ORG_DATATYPES, SCHEMA_ORG_PROPERTIES, SCHEMA_ORG_TYPES } from "../../src/rules/schema-org/vocabulary.generated.js";
import {
  ancestors,
  descendants,
  isKnownType,
  isSubtypeOf,
  propertyAppliesTo,
  propertyDef,
  rangeAccepts,
} from "../../src/rules/schema-org/vocabulary.js";

describe("schema.org vocabulary", () => {
  it("walks the type hierarchy", () => {
    expect(isSubtypeOf("Restaurant", "LocalBusiness")).toBe(true);
    expect(isSubtypeOf("Restaurant", "Organization")).toBe(true);
    expect(isSubtypeOf("Product", "Organization")).toBe(false);
    expect(ancestors("Restaurant").has("Restaurant")).toBe(true);
    expect(ancestors("Restaurant")).toBe(ancestors("Restaurant"));
    expect(() => ancestors("NoSuchType")).toThrow(/NoSuchType/);
    expect(isKnownType("Product")).toBe(true);
    expect(isKnownType("NoSuchType")).toBe(false);
  });

  it("lists descendants, sorted, including the type itself", () => {
    const d = descendants("Organization");
    expect(d).toContain("Restaurant");
    expect(d).toContain("Corporation");
    expect(d).toContain("Organization");
    expect([...d]).toEqual([...d].sort());
  });

  it("applies a property through the domain's descendants", () => {
    expect(propertyAppliesTo("name", ["Product"])).toBe(true);
    expect(propertyAppliesTo("recipeIngredient", ["Product"])).toBe(false);
    expect(propertyDef("name")?.domain).toContain("Thing");
    expect(propertyDef("noSuchProperty")).toBeUndefined();
  });

  it("checks ranges through subtypes, Thing and the Role pattern", () => {
    expect(rangeAccepts("offers", ["Offer"])).toBe(true);
    expect(rangeAccepts("offers", ["AggregateOffer"])).toBe(true);
    expect(rangeAccepts("author", ["Person"])).toBe(true);
    expect(rangeAccepts("author", ["Offer"])).toBe(false);
    for (const p of Object.keys(SCHEMA_ORG_PROPERTIES)) {
      expect(rangeAccepts(p, ["Role"])).toBe(true);
      expect(rangeAccepts(p, ["OrganizationRole"])).toBe(true);
    }
  });

  it("keeps the Quantity family as types, not datatypes", () => {
    expect(isKnownType("Duration")).toBe(true);
    expect(() => ancestors("Distance")).not.toThrow();
    expect(isSubtypeOf("Mass", "Quantity")).toBe(true);
    expect(rangeAccepts("cookTime", ["Duration"])).toBe(true);
    expect(rangeAccepts("height", ["Distance"])).toBe(true);
    expect(rangeAccepts("weight", ["Mass"])).toBe(true);
    expect(rangeAccepts("cookTime", ["NoSuchType"])).toBe(false);
    expect(SCHEMA_ORG_DATATYPES).toContain("Text");
    expect(SCHEMA_ORG_DATATYPES).not.toContain("Duration");
    expect(SCHEMA_ORG_DATATYPES).not.toContain("Quantity");
  });

  it("records pending and superseded properties", () => {
    const defs = Object.values(SCHEMA_ORG_PROPERTIES);
    expect(defs.some((d) => d.status === "pending")).toBe(true);
    const superseded = defs.filter((d) => d.status === "superseded");
    expect(superseded.length).toBeGreaterThan(0);
    expect(superseded.some((d) => d.supersededBy !== undefined && propertyDef(d.supersededBy) !== undefined)).toBe(true);
  });

  it("drops attic terms and enumeration members", () => {
    expect(isKnownType("StupidType")).toBe(false);
    expect(propertyDef("stupidProperty")).toBeUndefined();
    expect("InStock" in SCHEMA_ORG_TYPES).toBe(false);
    expect(isKnownType("ItemAvailability")).toBe(true);
  });

  it("carries a provenance header naming release, sha256 and date", () => {
    const head = readFileSync(new URL("../../src/rules/schema-org/vocabulary.generated.ts", import.meta.url), "utf8").slice(0, 2000);
    expect(head).toMatch(/GENERATED by scripts\/derive-schema-org\.ts\. Do not edit by hand/);
    expect(head).toMatch(/Release:\s+\d+(\.\d+)?\n/);
    expect(head).toMatch(/Source sha256:\s+[0-9a-f]{64}\n/);
    expect(head).toMatch(/Release date:\s+\d{4}-\d{2}-\d{2}\n/);
    expect(head).toMatch(/CC BY-SA 3\.0/);
  });
});
